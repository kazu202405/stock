-- ============================================================
-- スコアが「全項目を判定できたか」を保存する
-- ============================================================
-- 2026-08-16。
--
-- 画面のスコアには2つの状態がある。
--   緑     … 12項目すべてを判定できた（充足度100%）
--   橙     … 判定できない項目があり、判定できた分だけで採点した暫定値
--
-- この区別は読み取り時に score_breakdown() で計算しており、DBには
-- 保存していなかった。そのため**並べ替えに使えない**。一覧は50件ずつ
-- サーバー側で区切っているので、取得後にブラウザで並べ替えると
-- ページをまたいだときに順序が崩れる。
--
-- 「同じスコアなら、全項目を判定できた方を上に出す」を実現するために、
-- 判定できたかどうかだけを列に持つ。スコアそのもの（match_rate）は
-- 従来どおり別列で、ここは並べ替えの第2キーとしてだけ使う。
--
-- 実測（2026-08-16 / 3,868銘柄）:
--   完全判定  326件 ( 8.4%)
--   暫定    3,473件 (89.8%)
--   判定不足   69件
-- 暫定が多いのは、12項目のうち「売上成長(予想)」「営利成長(予想)」が
-- 業績予想を必要とし、それが9%しか埋まっていないため。
-- ============================================================

ALTER TABLE screened_latest
  ADD COLUMN IF NOT EXISTS score_complete BOOLEAN;

COMMENT ON COLUMN screened_latest.score_complete IS
  'スコアの12項目すべてを判定できたか。一覧で「同じスコアなら完全判定を上」に並べるための第2キー';

-- 並べ替えは「スコア降順 → 完全判定を上」。この順の複合インデックスを張る。
CREATE INDEX IF NOT EXISTS idx_screened_latest_score_order
  ON screened_latest (match_rate DESC, score_complete DESC);
