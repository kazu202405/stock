-- ============================================================
-- 予想配当（年換算）と予想配当利回りを持つ
-- ============================================================
-- 2026-08-14。
--
-- これまで画面に出していた配当利回りは「直近12か月に実際に支払われた
-- 配当 ÷ 株価」＝実績だった。実績は決算期をまたぐため、期末配当と翌期の
-- 中間配当が重なった年は実態より高く出る（367A: 105円＋60円＝165円で
-- 6.18%。会社が想定している年間配当は120円で4.24%）。
--
-- 日本の投資家が「配当利回り」として見慣れているのは予想ベースなので、
-- 実績と予想の両方を持ち、どちらの数字かを画面に明示する。
--
-- dps_forecast は Yahoo の forward dividend rate（直近の配当を年換算した
-- 値）で、企業が開示した会社予想そのものではない。画面のラベルも
-- 「予想（年換算）」とし、会社予想と言い切らない。
--
-- 値が信用できないときは NULL を入れる。誤った数字を出し続けるより
-- 「不明」の方がよい（2026-08-12 の利回り47%事故と同じ方針）。
-- ============================================================

ALTER TABLE screened_latest
  ADD COLUMN IF NOT EXISTS dps_forecast          NUMERIC,
  ADD COLUMN IF NOT EXISTS dividend_yield_forward NUMERIC;

COMMENT ON COLUMN screened_latest.dps_forecast IS
  '予想1株配当（円）。Yahooのforward dividend rate＝直近配当の年換算。会社開示の予想そのものではない';
COMMENT ON COLUMN screened_latest.dividend_yield_forward IS
  '予想配当利回り(%)。dps_forecast ÷ 株価。検証に通らなければNULL';
